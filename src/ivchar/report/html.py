def _b64(path: Path) -> str:
    return base64.b64encode(Path(path).read_bytes()).decode()


def _fmt(x):
    if isinstance(x, (float, np.floating)):
        if not np.isfinite(x):
            return "-"
        return f"{x:.3e}" if (abs(x) < 1e-2 and x != 0) or abs(x) >= 1e4 else f"{x:.4g}"
    return x


def _table(df: pd.DataFrame, index=False) -> str:
    if df is None or df.empty:
        return "<p class='meta'>None.</p>"
    return df.map(_fmt).to_html(index=index, border=0, escape=True)


def _spec_text(spec: dict) -> str:
    parts = []
    for col, (lo, hi) in spec.items():
        if lo is not None and hi is not None:
            parts.append(f"{_fmt(lo)} ≤ {col} ≤ {_fmt(hi)}")
        elif lo is not None:
            parts.append(f"{col} ≥ {_fmt(lo)}")
        else:
            parts.append(f"{col} ≤ {_fmt(hi)}")
    return "; ".join(parts) or "none"


def render(analysis: Analysis, figures: dict[str, Path], out_path: Path, simulated: bool,
           device: str, ai_summary: str | None = None, ai_model: str | None = None,
           z_threshold: float = 3.5) -> Path:
    p = analysis.params
    wide_keys = ["idvg_corners", "idvg_temp"]
    flagged = p[p.outlier]
    yields = analysis.yields
    overall = (100 * analysis.spec_rows["pass"].mean()) if len(analysis.spec_rows) else np.nan
    kpis = [
        {"value": f"{p['die'].nunique()}", "label": "dies per corner"},
        {"value": ", ".join(sorted(p.corner.unique())), "label": "corners"},
        {"value": ", ".join(f"{t:g}" for t in sorted(p.temp_c.unique())), "label": "temperatures (°C)"},
        {"value": "-" if np.isnan(overall) else f"{overall:.1f}%", "label": f"yield at {analysis.spec_temp_c:g} °C"},
        {"value": f"{flagged.drop_duplicates(['corner', 'die']).shape[0]}", "label": "dies with outliers"},
    ]
    fails = analysis.spec_rows
    fails = fails.loc[~fails["pass"], ["corner", "die", "fail_reason"]] if len(fails) else None
    injected = (p.loc[p.injected_defect != "", ["corner", "die", "injected_defect"]].drop_duplicates()
                if simulated and "injected_defect" in p else None)
    summary = analysis.summary.xs("median", axis=1, level=1) if len(analysis.summary) else analysis.summary

    html = TEMPLATE.render(
        simulated=simulated,
        meta={"device": device, "n_devices": len(p), "version": __version__,
              "generated": dt.datetime.now().strftime("%Y-%m-%d %H:%M")},
        kpis=kpis,
        ai_summary=ai_summary, ai_model=ai_model,
        spec_temp=f"{analysis.spec_temp_c:g}",
        yield_html=_table(yields.reset_index() if len(yields) else yields),
        spec_text=_spec_text(analysis.spec),
        fail_html=_table(fails) if fails is not None and len(fails) else "",
        z_threshold=z_threshold,
        outlier_html=_table(flagged[["corner", "die", "temp_c", "outlier_reason"]]),
        injected_html=_table(injected) if injected is not None and len(injected) else "",
        figures_wide=[_b64(figures[k]) for k in wide_keys if k in figures],
        figures=[_b64(v) for k, v in figures.items() if k not in wide_keys],
        summary_html=_table(summary.reset_index()),
    )
    out_path.write_text(html, encoding="utf-8")
    return out_path
